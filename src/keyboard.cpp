std::uint8_t at_code(SDL_Scancode key) {
    constexpr std::array<std::uint8_t, 26> letters{
        0x1c, 0x32, 0x21, 0x23, 0x24, 0x2b, 0x34, 0x33, 0x43,
        0x3b, 0x42, 0x4b, 0x3a, 0x31, 0x44, 0x4d, 0x15, 0x2d,
        0x1b, 0x2c, 0x3c, 0x2a, 0x1d, 0x22, 0x35, 0x1a};
    constexpr std::array<std::uint8_t, 10> digits{
        0x16, 0x1e, 0x26, 0x25, 0x2e, 0x36, 0x3d, 0x3e, 0x46, 0x45};
    constexpr std::array<std::uint8_t, 12> functions{
        0x05, 0x06, 0x04, 0x0c, 0x03, 0x0b, 0x83, 0x0a, 0x01, 0x09, 0x78, 0x07};
    constexpr std::array<std::uint8_t, 10> keypad{
        0x69, 0x72, 0x7a, 0x6b, 0x73, 0x74, 0x6c, 0x75, 0x7d, 0x70};
    if (key >= SDL_SCANCODE_A && key <= SDL_SCANCODE_Z)
        return letters[static_cast<std::size_t>(key - SDL_SCANCODE_A)];
    if (key >= SDL_SCANCODE_1 && key <= SDL_SCANCODE_0)
        return digits[static_cast<std::size_t>(key - SDL_SCANCODE_1)];
    if (key >= SDL_SCANCODE_F1 && key <= SDL_SCANCODE_F12)
        return functions[static_cast<std::size_t>(key - SDL_SCANCODE_F1)];
    if (key >= SDL_SCANCODE_KP_1 && key <= SDL_SCANCODE_KP_0)
        return keypad[static_cast<std::size_t>(key - SDL_SCANCODE_KP_1)];
    switch (key) {
    case SDL_SCANCODE_RETURN: return 0x5a;
    case SDL_SCANCODE_ESCAPE: return 0x76;
    case SDL_SCANCODE_BACKSPACE: return 0x66;
    case SDL_SCANCODE_TAB: return 0x0d;
    case SDL_SCANCODE_SPACE: return 0x29;
    case SDL_SCANCODE_MINUS: return 0x4e;
    case SDL_SCANCODE_EQUALS: return 0x55;
    case SDL_SCANCODE_LEFTBRACKET: return 0x54;
    case SDL_SCANCODE_RIGHTBRACKET: return 0x5b;
    case SDL_SCANCODE_BACKSLASH: case SDL_SCANCODE_NONUSHASH: return 0x5d;
    case SDL_SCANCODE_SEMICOLON: return 0x4c;
    case SDL_SCANCODE_APOSTROPHE: return 0x52;
    case SDL_SCANCODE_GRAVE: return 0x0e;
    case SDL_SCANCODE_COMMA: return 0x41;
    case SDL_SCANCODE_PERIOD: return 0x49;
    case SDL_SCANCODE_SLASH: return 0x4a;
    case SDL_SCANCODE_KP_MINUS: return 0x7b;
    case SDL_SCANCODE_KP_PLUS: return 0x79;
    case SDL_SCANCODE_KP_MULTIPLY: return 0x7c;
    case SDL_SCANCODE_KP_PERIOD: return 0x71;
    default: return 0;
    }
}

std::size_t navigation_index(SDL_Scancode key) {
    switch (key) {
    case SDL_SCANCODE_END: return 0x84;
    case SDL_SCANCODE_LEFT: return 0x86;
    case SDL_SCANCODE_HOME: return 0x87;
    case SDL_SCANCODE_INSERT: return 0x8b;
    case SDL_SCANCODE_DELETE: return 0x8c;
    case SDL_SCANCODE_DOWN: return 0x8d;
    case SDL_SCANCODE_RIGHT: return 0x8f;
    case SDL_SCANCODE_UP: return 0x90;
    case SDL_SCANCODE_PAGEDOWN: return 0x95;
    case SDL_SCANCODE_PAGEUP: return 0x98;
    default: return 0;
    }
}
