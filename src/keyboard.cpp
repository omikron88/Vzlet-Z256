void Keyboard::set_czech(bool enabled) {
    czech_ = enabled;
    acute_ = caron_ = false;
    alt_pending_.reset();
}

void Keyboard::release() {
    scroll_ = acute_ = caron_ = false;
    hex_high_.reset();
    alt_pending_.reset();
}

std::uint8_t Keyboard::output(std::uint8_t byte) const {
    return czech_ && byte >= 0xc0 ? static_cast<std::uint8_t>(byte ^ 0x20) : byte;
}

std::optional<std::uint8_t> Keyboard::handle_event(const SDL_KeyboardEvent& event) {
    if (event.type == SDL_EVENT_KEY_UP) {
        if (alt_pending_ == event.scancode) {
            set_czech(!czech_);
            alt_pending_.reset();
        }
        if (event.scancode == SDL_SCANCODE_SCROLLLOCK) {
            scroll_ = false;
            hex_high_.reset();
        }
        return std::nullopt;
    }
    if (event.type != SDL_EVENT_KEY_DOWN) return std::nullopt;
    switch (event.scancode) {
    case SDL_SCANCODE_LALT: case SDL_SCANCODE_RALT:
        // Z_ALT's toggle is commented out in the supplied firmware. Enable its
        // intended action on a standalone Alt release, so Alt+Enter/Alt+Tab
        // remain host shortcuts and do not change the converter's layout.
        if (!event.repeat) alt_pending_ = event.scancode;
        return std::nullopt;
    default: break;
    }
    alt_pending_.reset();
    switch (event.scancode) {
    case SDL_SCANCODE_CAPSLOCK:
        if (!event.repeat) caps_ = !caps_;
        return std::nullopt;
    case SDL_SCANCODE_NUMLOCKCLEAR:
        if (!event.repeat) num_ = !num_;
        return std::nullopt;
    case SDL_SCANCODE_SCROLLLOCK:
        scroll_ = true;
        hex_high_.reset();
        return std::nullopt;
    default: break;
    }
    const bool shift = (event.mod & SDL_KMOD_SHIFT) != 0;
    // EXTEND handles these keys outside the alphabet/Ctrl/accent/hex path.
    if (event.scancode == SDL_SCANCODE_KP_ENTER) return output(0x0d);
    if (event.scancode == SDL_SCANCODE_KP_DIVIDE) return output('/');
    if (const auto index = navigation_index(event.scancode); index != 0) {
        if (num_) return std::nullopt;
        const auto byte = us_lower[index + (shift ? 21U : 0U)];
        return byte == 0 ? std::nullopt : std::optional{output(byte)};
    }
    const auto code = at_code(event.scancode);
    if (code == 0) return std::nullopt;
    if (czech_ && code == 0x55) {
        if (shift) caron_ = true;
        else acute_ = true;
        return std::nullopt;
    }
    // CAPS_ON/SHIFTON choose the shifted table using Caps XOR Shift, including
    // punctuation and digits, unlike the host's normal Caps Lock behavior.
    const bool upper = caps_ != shift;
    auto byte = czech_ ? (upper ? cz_upper[code] : cz_lower[code])
                       : (upper ? us_upper[code] : us_lower[code]);
    if (byte == 0) return std::nullopt;
    if (scroll_) {
        std::uint8_t nibble{};
        if (byte >= '0' && byte <= '9') nibble = static_cast<std::uint8_t>(byte - '0');
        else if (byte >= 'a' && byte <= 'f') nibble = static_cast<std::uint8_t>(byte - 'a' + 10);
        else if (byte >= 'A' && byte <= 'F') nibble = static_cast<std::uint8_t>(byte - 'A' + 10);
        else return std::nullopt;
        if (!hex_high_) {
            hex_high_ = nibble;
            return std::nullopt;
        }
        byte = static_cast<std::uint8_t>(*hex_high_ * 16 + nibble);
        hex_high_.reset();
    } else if (czech_ && (acute_ || caron_)) {
        const auto& accents = acute_ ? acute : caron;
        const auto base = static_cast<std::uint8_t>((byte & 0x7f) & ~0x20);
        if (base >= 'A' && base <= 'Z' && accents[base - 'A'] != 0)
            byte = static_cast<std::uint8_t>(accents[base - 'A'] + (shift ? 0x20 : 0));
        if (acute_) acute_ = false;
        else caron_ = false;
    } else if ((event.mod & SDL_KMOD_CTRL) != 0) {
        const auto ascii = static_cast<std::uint8_t>(byte & 0x7f);
        if (ascii < '?') return std::nullopt;
        // '?' is transmitted unchanged; '@' and above become 00..1f.
        if (ascii != '?') byte = static_cast<std::uint8_t>(ascii & 0x1f);
    }
    return output(byte);
}

